import { spawn, execFileSync } from 'node:child_process';
import { cp, mkdir, readFile, writeFile, rm, access, symlink, stat } from 'node:fs/promises';
import { join, resolve, relative, isAbsolute } from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import { classicRoot, repository, deploymentRoot, configuration, writeJson, readJson, runtimeEnvironment } from './common.mjs';
import { pruneReleases } from './prune-releases.mjs';
import { executableName } from './platform.mjs';
import { stagePublicAssets } from './public-assets.mjs';
import { copyStandalone } from './standalone.mjs';

const config = await configuration();
const stageOnly = process.argv.includes('--stage');
const environment = { ...await runtimeEnvironment(config), ...config.buildEnvironment };
const webOnly = process.platform === 'win32' || process.argv.includes('--web-only');
const webRoot = join(classicRoot, 'apps/web');
const releasesRoot = resolve(config.releasesRoot || join(deploymentRoot, 'releases'));
const buildDir = '.next-local-production';
const statusPath = join(deploymentRoot, 'build.json');
const lockPath = join(deploymentRoot, 'build.lock');
let ownsLock = false;
async function status(phase, extra = {}) {
  console.log(`[production] ${phase}`);
  await writeJson(statusPath, { phase, running: true, updatedAt: new Date().toISOString(), ...extra });
}
function run(command, args, cwd = classicRoot, extra = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd, windowsHide: true, stdio: 'inherit', detached: process.platform !== 'win32', env: {
      ...environment, ...extra,
    } });
    const terminate = () => { try { if (process.platform === 'win32') child.kill('SIGTERM'); else process.kill(-child.pid, 'SIGTERM'); } catch {} };
    process.once('SIGTERM', terminate);
    child.once('error', reject);
    child.once('exit', (code, signal) => {
      process.removeListener('SIGTERM', terminate);
      code === 0 ? resolve() : reject(Error(`${command} failed (${code ?? signal})`));
    });
  });
}
async function sourceFingerprint() {
  const files = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], { cwd: repository, maxBuffer: 64 * 1024 ** 2 }).toString().split('\0').filter(Boolean).sort();
  const hash = createHash('sha256');
  for (const file of files) {
    // next-env.d.ts is generated by Next, not application source.
    if (file.endsWith('/next-env.d.ts')) continue;
    if (!/^(classic\/(apps\/(web|electron\/app)|rust|packages|patches|scripts)\/|apps\/mcp\/|crates\/|resources\/|Cargo\.(toml|lock)$|classic\/(package\.json|bun\.lock)$)/.test(file)) continue;
    hash.update(file);
    try { hash.update(await readFile(join(repository, file))); }
    catch (error) { if (error.code === 'ENOENT') hash.update('deleted'); else throw error; }
  }
  return hash.digest('hex');
}

try {
  const stale = await readJson(lockPath);
  if (stale) {
    let alive = true;
    try { process.kill(stale.pid, 0); } catch { alive = false; }
    if (alive) throw Error('Another production build is already running.');
    await rm(lockPath);
  }
  await writeFile(lockPath, JSON.stringify({ pid: process.pid }), { flag: 'wx', mode: 0o600 });
  ownsLock = true;
  await status('Checking local source');
  const fingerprint = await sourceFingerprint();
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repository }).toString().trim();
  const branch = execFileSync('git', ['branch', '--show-current'], { cwd: repository }).toString().trim();
  const dirty = !!execFileSync('git', ['status', '--porcelain'], { cwd: repository, maxBuffer: 64 * 1024 ** 2 }).toString().trim();
  await status('Building canonical Rust / WASM');
  await run(config.bun, ['run', 'build:wasm']);
  await status('Preparing local assets');
  await run(config.node, ['scripts/prepare-earshot-runtime.mjs']);
  await run(config.node, ['scripts/prepare-hyperframes-references.mjs']);
  const publicStage = join(deploymentRoot, 'build-assets', randomUUID());
  const restoredAssets = await stagePublicAssets({ repository, publicRoot: join(webRoot, 'public'), destination: publicStage, commit });
  await run(config.node, ['scripts/verify-background-removal-assets.mjs', '--public-root', publicStage], webRoot);
  await status('Building local control plane');
  await run('cargo', ['build', '--locked', '--release', '-p', 'opencut-mcp-server', '--bins'], repository);
  await status('Building optimized production editor');
  await run(config.node, [join(webRoot, 'node_modules/next/dist/bin/next'), 'build', '--webpack'], webRoot, {
    NODE_ENV: 'production', OPENCUT_RUNTIME_TARGET: 'browser', OPENCUT_BUILD_DIR: buildDir,
  });
  if (await sourceFingerprint() !== fingerprint)
    throw Error('Source changed during the build. Current production was preserved; rebuild when editing is finished.');
  await status('Packaging standalone release');
  const id = `${new Date().toISOString().replace(/[:.]/g, '-')}-${commit.slice(0, 8)}`;
  const release = join(releasesRoot, id);
  await mkdir(release, { recursive: true, mode: 0o700 });
  await copyStandalone({ source: join(webRoot, buildDir, 'standalone'), destination: join(release, 'server'), tracingRoot: classicRoot });
  // Next's tracing root is classic/, so the standalone entry is apps/web/server.js.
  const appRoot = join(release, 'server/apps/web');
  await cp(join(webRoot, buildDir, 'static'), join(appRoot, buildDir, 'static'), { recursive: true });
  await cp(publicStage, join(appRoot, 'public'), { recursive: true, verbatimSymlinks: true });
  const stagedRelative = relative(resolve(deploymentRoot, 'build-assets'), resolve(publicStage));
  if (!stagedRelative || stagedRelative.startsWith('..') || isAbsolute(stagedRelative) || !/^[a-f0-9-]{36}$/.test(stagedRelative))
    throw Error('Refusing to clean a public staging directory outside this build');
  await rm(resolve(publicStage), { recursive: true });
  if (!webOnly) await cp(join(classicRoot, 'apps/electron/app'), join(release, 'electron'), { recursive: true, dereference: true });
  const nativeTarget = resolve(repository, environment.CARGO_TARGET_DIR || 'target');
  await cp(join(nativeTarget, 'release', executableName('opencut-mcp')), join(release, executableName('opencut-mcp')));
  await cp(join(nativeTarget, 'release', executableName('opencut-session-policy')), join(release, executableName('opencut-session-policy')));
  await cp(join(classicRoot, 'scripts/local-subject-framing'), join(release, 'server/scripts/local-subject-framing'), { recursive: true });
  const detector = join(classicRoot, '.local/subject-framing');
  try {
    await access(detector);
    await mkdir(join(release, 'server/.local'), { recursive: true });
    const packagedDetector = join(release, 'server/.local/subject-framing');
    try {
      await symlink(detector, packagedDetector, process.platform === 'win32' ? 'junction' : 'dir');
    } catch (error) {
      // Next's standalone trace may already contain the detector snapshot.
      if (error.code !== 'EEXIST' || !(await stat(packagedDetector)).isDirectory()) throw error;
    }
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  // Pin the shell binary as well as its source to this release.
  const electronPackage = JSON.parse(await readFile(join(classicRoot, 'apps/electron/package.json'), 'utf8'));
  if (!webOnly) {
    const { createRequire } = await import('node:module');
    const require = createRequire(join(classicRoot, 'apps/electron/package.json'));
    const electronBinary = require('electron');
    const electronApp = electronBinary.slice(0, electronBinary.indexOf('/Contents/MacOS/'));
    if (!electronApp.endsWith('.app')) throw Error('Electron packaging currently supports macOS; use --web-only for browser production.');
    await cp(electronApp, join(release, 'Electron.app'), { recursive: true, verbatimSymlinks: true });
  }
  const buildId = (await readFile(join(webRoot, buildDir, 'BUILD_ID'), 'utf8')).trim();
  const metadata = { id, directory: release, commit, branch, dirty, fingerprint, builtAt: new Date().toISOString(), appRoot,
    buildId, platform: process.platform, webOnly, restoredAssets,
    authentication: { clientId: environment.OPENCUT_LEGITATE_CLIENT_ID || '', legitateOnly: environment.OPENCUT_LEGITATE_ONLY === 'true' },
    electronVersion: webOnly ? null : electronPackage.devDependencies.electron };
  await status('Verifying production release');
  // Startup smoke check happens on an ephemeral port without touching accounts.
  const { createServer } = await import('node:net');
  const probe = createServer();
  await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = probe.address().port;
  await new Promise(resolve => probe.close(resolve));
  const smoke = spawn(config.node, [join(appRoot, 'server.js')], { cwd: appRoot, windowsHide: true, stdio: 'inherit',
    env: { ...environment, NODE_ENV: 'production', PORT: String(port), HOSTNAME: '127.0.0.1',
      OPENCUT_ACCOUNTS_DIR: config.accountsRoot, NEXT_TELEMETRY_DISABLED: '1',
      OPENCUT_SESSION_POLICY_BINARY: environment.OPENCUT_SESSION_POLICY_BINARY ?? join(release, executableName('opencut-session-policy')) } });
  try {
    let healthy = false;
    for (let attempt = 0; attempt < 90; attempt++) {
      if (smoke.exitCode !== null) break;
      try {
        const response = await fetch(`http://127.0.0.1:${port}/`, { signal: AbortSignal.timeout(1000) });
        if (response.ok) { healthy = true; break; }
      } catch {}
      await new Promise(resolve => setTimeout(resolve, 250));
    }
    if (!healthy) throw Error('Production startup smoke check failed; previous release retained.');
  } finally { smoke.kill('SIGTERM'); }
  await writeJson(join(release, 'release.json'), { ...metadata, startupSmokePassed: true });
  // Atomic activation: a failed build never changes this pointer.
  if (stageOnly) {
    await writeJson(join(deploymentRoot, 'candidate.json'), metadata);
  } else {
    const previous = await readJson(join(deploymentRoot, 'current.json'));
    if (previous) await writeJson(join(deploymentRoot, 'previous.json'), previous);
    await writeJson(join(deploymentRoot, 'current.json'), metadata);
  }
  await status(stageOnly ? 'Candidate ready (not activated)' : 'Production ready', { running: false, release: metadata });
  // Retain active/rollback/candidate and three newest verified builds. Repeated
  // local deployment must not consume the audio decoder's scratch disk space.
  try { console.log('[production] Release retention', await pruneReleases({ deploymentRoot, releasesRoot })); }
  catch (error) { console.warn('[production] Release cleanup skipped:', error.message); }
} catch (error) {
  console.error(error);
  if (ownsLock) await status('Build failed', { running: false, error: error.message });
  process.exitCode = 1;
} finally {
  if (ownsLock) await rm(lockPath, { force: true });
}
